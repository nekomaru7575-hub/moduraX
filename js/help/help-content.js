/**
 * 「コマンド一覧」のノードを組む。本体機能のぶんは常に出し、システム固有のぶんは
 * その部屋に適用中のシステムのものだけを出す（打てないコマンドを並べても迷わせるだけなので）。
 *
 * @param {string|null} activePlugin room.activePlugin の値
 * @returns {{ id: string, label: string, body: string[], children: Array }}
 */
export function buildCommandListHelp(activePlugin) {
  const pluginNode = activePlugin ? PLUGIN_COMMAND_HELP[activePlugin] : null;
  return {
    id: 'commands',
    label: 'コマンド一覧',
    body: ['チャット欄に打てるコマンドの一覧。'],
    children: pluginNode ? [COMMAND_LIST_CORE, pluginNode] : [COMMAND_LIST_CORE]
  };
}

