// js/help/help-content.js
// 部屋の中のヘルプ（「？ヘルプ」タブ）で読ませる文章そのもの。
// ここにあるのはデータだけで、描画も遷移も js/help/help-panel.js が持つ。
//
// 【書き足し方】
// ヘルプの1項目（ノード）は次の形。該当するノードの children に1件足せば増える。
//
//   { id, label, body, children }
//     id       … 一意な文字列。パネル側がどこを開いているか覚えるのに使うだけ
//     label    … 選択肢のボタンに出る文字。短く、名詞で
//     body     … 選んだときにボットが喋る本文。文字列の配列＝段落。省略可
//     children … さらに深い選択肢の配列。無い／空＝終端（パネルが戻る導線を出す）
//
// 【1項目5行まで】bodyは5要素を超えないこと。それより長くなるなら、その項目を
// 説明の入口（bodyは1〜2行だけ）にして、下位のchildrenへ切り分ける。読み手は選択肢を
// 押した直後に全部読むので、6行以上が一度に並ぶと吹き出しの中で迷子になる。
//
// 【例外】「コマンド一覧」（COMMAND_LIST_CORE と PLUGIN_COMMAND_HELP）だけは、行数を
// 制限せず、文体も地の文にする。理由はその節の頭に書いてある。
//
// 【何を書くか】「ユーザーがやりたいこと」と「実装されている機能」を突き合わせるのが
// ヘルプの役割。どこを押せば何ができるかまでを書き、内部の規則や例外の細目は書かない
// （それはコードのコメントと docs/ の仕事）。
//
// 本文はHTMLとして解釈されない（パネル側がtextContentで入れる）。タグを書いても
// そのまま文字として出るだけなので、記号は素直に書いてよい。
//
// プラグイン（ゲームシステム固有）の説明もここへまとめて書く。プラグイン記述子
// （js/parameters/*.js）側には何も足さない：ヘルプの文体・粒度をこの1ファイルで
// 揃えたいのと、記述子を「ルールの実装」だけに保ちたいため。

// あいさつ。ヘルプを開くたび／「最初にもどる」のたびにこの中から1つ選ぶ。
// 増やすときはここに1行足すだけ。
