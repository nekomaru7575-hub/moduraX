/**
 * この部屋で出すヘルプのルート層を組む。
 * 「プラグイン機能のこと」は、その部屋に適用中のシステムのぶんだけ出す
 * （関係の無いシステムの説明を並べても迷わせるだけなので）。
 * 「コマンド一覧」も同じ考え方で、中身をbuildCommandListHelpが絞る。
 *
 * @param {string|null} activePlugin room.activePlugin の値
 * @returns {{ id: string, label: string, children: Array }}
 */
export function buildHelpRoot(activePlugin) {
  const pluginNode = activePlugin ? PLUGIN_HELP[activePlugin] : null;
  const commandNode = buildCommandListHelp(activePlugin);
  return {
    id: 'root',
    label: '最初にもどる',
    children: pluginNode
      ? [CORE_HELP, pluginNode, commandNode, whoIsDediDevi, howToEraceYou]
      : [CORE_HELP, commandNode, whoIsDediDevi, howToEraceYou]
  };
}
